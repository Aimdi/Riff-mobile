import 'package:audio_service/audio_service.dart';
import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:harmonymusic/services/song_credits.dart';
import 'package:harmonymusic/ui/theme/riff_theme.dart';
import 'package:harmonymusic/ui/widgets/song_credits_dialog.dart';

/// Notes as YouTube writes them for a track a distributor sent it.
const _notes = '''Provided to YouTube by The Orchard Enterprises

Midnight City · M83 · Anthony  Gonzalez

Star Wars: Hurry Up, We're Dreaming

℗ 2011 Naïve

Released on: 2011-10-18

Producer: Justin Meldal-Johnsen
Producer: Anthony Gonzalez
Composer, Lyricist: Anthony Gonzalez
Mixing  Engineer: Tony Hoffer

Auto-generated by YouTube.''';

void main() {
  test("a track's credits, as YouTube's notes give them", () {
    final c = parseSongCredits(_notes)!;
    expect(c.providedBy, 'The Orchard Enterprises');
    expect(c.performers, ['M83', 'Anthony Gonzalez']);
    expect(c.source, '℗ 2011 Naïve');
    expect(c.released, '2011-10-18');
    // In the order listed, one row per role; "Composer, Lyricist" credits
    // both, and the album's "Star Wars: …" isn't a role.
    expect([
      for (final (role, names) in c.roles) '$role: ${names.join(', ')}'
    ], [
      'Producer: Justin Meldal-Johnsen, Anthony Gonzalez',
      'Composer: Anthony Gonzalez',
      'Lyricist: Anthony Gonzalez',
      'Mixing Engineer: Tony Hoffer',
    ]);
  });

  test("a music video's own notes credit nothing", () {
    expect(
        parseSongCredits('Official video. Director: Someone\n'
            'Follow us: https://example.com'),
        isNull);
    expect(parseSongCredits(''), isNull);
  });

  group('loaded once per song', () {
    var asked = 0;
    Object? failure;
    setUp(() {
      asked = 0;
      failure = null;
      SongCreditsService.fetchDescription = (id) async {
        asked++;
        if (failure != null) throw failure!;
        return id == 'song' ? _notes : 'Just a video.';
      };
    });

    test('remembered, a song without credits too; a failure is not', () async {
      expect((await SongCreditsService.load('song'))!.performers,
          ['M83', 'Anthony Gonzalez']);
      await SongCreditsService.load('song');
      expect(asked, 1);
      expect(await SongCreditsService.load('video'), isNull);
      expect(await SongCreditsService.load('video'), isNull);
      expect(asked, 2);

      failure = Exception('offline');
      await expectLater(SongCreditsService.load('later'), throwsException);
      failure = null;
      expect((await SongCreditsService.load('later')), isNull);
      expect(asked, 4);
    });

    Future<void> open(WidgetTester tester, String id) async {
      tester.view.physicalSize = const Size(800, 1600);
      tester.view.devicePixelRatio = 1;
      addTearDown(tester.view.reset);
      await tester.pumpWidget(MaterialApp(
        theme: RiffTheme.dark(const Color(0xFF1DB954)),
        home: Scaffold(
          body: SongCreditsDialog(song: MediaItem(id: id, title: 'Title')),
        ),
      ));
      await tester.pumpAndSettle();
    }

    testWidgets('the dialog lists them', (tester) async {
      await open(tester, 'song');
      expect(find.text('CREDITSPERFORMEDBY'), findsOneWidget);
      expect(find.text('M83, Anthony Gonzalez'), findsOneWidget);
      expect(find.text('PRODUCER'), findsOneWidget);
      expect(
          find.text('Justin Meldal-Johnsen, Anthony Gonzalez'), findsOneWidget);
      expect(find.text('18 Oct 2011'), findsOneWidget);
      expect(find.text('℗ 2011 Naïve'), findsOneWidget);
    });

    testWidgets('none for a video', (tester) async {
      await open(tester, 'clip');
      expect(find.text('noCredits'), findsOneWidget);
    });

    testWidgets('offline: say so, and Retry', (tester) async {
      failure = Exception('offline');
      await open(tester, 'retry-me');
      expect(find.text('creditsLoadFailed'), findsOneWidget);
      failure = null;
      await tester.tap(find.text('retry'));
      await tester.pumpAndSettle();
      expect(find.text('noCredits'), findsOneWidget);
    });
  });
}
